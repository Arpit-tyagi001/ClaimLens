"""Write the contract fixtures from the synthetic PDFs (work division, H2-4 task).

    python -m eval.make_fixtures          # writes contracts/fixtures/*.json

Writes into contracts/fixtures/. The files are
produced by the real code, so M1, M2 and M3 build against true shapes.
"""

from pathlib import Path

from docint.claimlens_docs import extract_policy_facts, extract_rejection, ingest_document

from .make_pdfs import OUT_DIR
from .make_pdfs import main as make_pdfs

FIXTURES_DIR = Path(__file__).parent.parent / "contracts" / "fixtures"


def _write(name: str, model) -> None:
    path = FIXTURES_DIR / name
    path.write_text(model.model_dump_json(indent=2) + "\n", encoding="utf-8")
    print(path)


def main() -> None:
    make_pdfs()
    FIXTURES_DIR.mkdir(exist_ok=True)
    policy = ingest_document(str(OUT_DIR / "synthetic_policy.pdf"), "pol", "policy")
    letter = ingest_document(str(OUT_DIR / "case_01_letter.pdf"), "let", "letter")
    _write("parsed_policy.json", policy)
    _write("parsed_letter.json", letter)
    _write("rejection_extraction.json", extract_rejection(letter))
    _write("policy_facts.json", extract_policy_facts(policy))
    (FIXTURES_DIR / "README.md").write_text(
        "# Fixtures (synthetic)\n\n"
        "Generated by `python -m eval.make_fixtures` from `eval/data/pdf/`. "
        "All documents are synthetic.\n\n"
        "Sources: policy = synthetic_policy.pdf, letter = case_01_letter.pdf.\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
